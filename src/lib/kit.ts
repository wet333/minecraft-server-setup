import { strToU8, zipSync, type Zippable } from "fflate";
import { APP_NAME, APP_URL } from "./brand";
import { buildCompose, extraPorts, playerMods, type PinnedProject } from "./compose";
import { EVERYDAY_COMMANDS, PLATFORMS, TROUBLESHOOTING, connectTips, startSteps } from "./guide";
import { downloadVersionFiles, fetchVersionFiles, type DownloadProgress } from "./modrinth";
import { type BuilderState, toProjectName } from "./state";

export const FABRIC_INSTALLER_URL = "https://fabricmc.net/use/installer/";

export function kitNames(state: BuilderState) {
  const project = toProjectName(state.serverName) || "minecraft";
  return {
    project,
    folder: project,
    zip: `${project}-server.zip`,
    /** Folder inside the kit, and the standalone zip, with the jars players copy into Minecraft. */
    playersFolder: "players",
    playersZip: `${project}-player-mods.zip`,
    instructions: "HOW-TO-INSTALL.txt",
    compose: "docker-compose.yml",
  };
}

const displayName = (state: BuilderState) => state.serverName.trim() || "Minecraft server";

/** Plain-text steps that travel with the mods folder, for players who never see this site. */
export function buildPlayerInstructions(state: BuilderState, mods: PinnedProject[] = playerMods(state)): string {
  const loader = state.loaderVersion ? ` and loader ${state.loaderVersion}` : "";
  const address = state.server.port === 25565 ? "the address the host gave you" : `the host's address followed by :${state.server.port}`;
  return [
    `How to join ${displayName(state)}`,
    "=".repeat(`How to join ${displayName(state)}`.length),
    "",
    `You need Minecraft Java Edition ${state.mcVersion} with the Fabric loader, plus every mod in the "mods" folder.`,
    "",
    "1. Install Fabric",
    `   Download the installer from ${FABRIC_INSTALLER_URL}, run it, choose Minecraft ${state.mcVersion}${loader},`,
    "   and click Install.",
    "",
    "2. Open your Minecraft folder",
    "   Windows: press Win+R, type %appdata%\\.minecraft and press Enter",
    "   macOS:   in Finder, Go > Go to Folder..., then ~/Library/Application Support/minecraft",
    "   Linux:   ~/.minecraft",
    "",
    "3. Copy the mods",
    `   Copy every .jar file from this "mods" folder into the "mods" folder there (create it if it`,
    "   does not exist). Move any mods you already had somewhere else first, so versions do not clash.",
    "",
    "4. Play",
    `   In the Minecraft Launcher pick the "fabric-loader-${state.mcVersion}" profile, start the game,`,
    `   then go to Multiplayer > Add Server and enter ${address}.`,
    "",
    `Using Prism Launcher, the Modrinth App or CurseForge? Create a Fabric ${state.mcVersion} instance and`,
    "copy the jars into that instance's mods folder instead.",
    "",
    "Mods included:",
    ...mods.map((m) => `- ${m.title} ${m.versionNumber}  (https://modrinth.com/mod/${m.slug})`),
    "",
    `Made with ${APP_NAME}. Mods are downloaded from Modrinth.`,
    "",
  ].join("\n");
}

/**
 * The jars every player must install, downloaded from Modrinth and checksum-verified.
 * Returns file name → contents, or null when players need nothing.
 */
export async function fetchPlayerMods(
  state: BuilderState,
  onProgress?: (p: DownloadProgress) => void,
): Promise<Map<string, Uint8Array> | null> {
  const mods = playerMods(state);
  if (mods.length === 0) return null;
  const files = await fetchVersionFiles(mods.map((m) => m.versionId));
  return downloadVersionFiles(files, onProgress);
}

/** Zip entries for the players' folder: mods/*.jar plus the install steps. Jars are already compressed. */
function playerEntries(state: BuilderState, jars: Map<string, Uint8Array>, prefix = ""): Zippable {
  const entries: Zippable = { [`${prefix}${kitNames(state).instructions}`]: strToU8(buildPlayerInstructions(state)) };
  for (const [name, data] of jars) entries[`${prefix}mods/${name}`] = [data, { level: 0 }];
  return entries;
}

const toBlob = (zipped: Uint8Array) => new Blob([zipped.slice().buffer as ArrayBuffer], { type: "application/zip" });

/** Standalone zip to send to friends: a mods folder and the install steps. */
export async function buildPlayerModsZip(state: BuilderState, onProgress?: (p: DownloadProgress) => void): Promise<Blob | null> {
  const jars = await fetchPlayerMods(state, onProgress);
  return jars ? toBlob(zipSync(playerEntries(state, jars))) : null;
}

const fence = (code: string) => ["```", code, "```"];

export function buildReadme(state: BuilderState): string {
  const names = kitNames(state);
  const port = state.server.port;
  const players = playerMods(state);
  const ctx = { zip: names.zip, folder: names.folder, port, storage: state.server.storage, memory: state.server.memory };
  const lines = [
    `# ${displayName(state)}`,
    "",
    `Fabric server for Minecraft ${state.mcVersion}, generated by ${APP_NAME} (${APP_URL}).`,
    "",
    "## Start the server",
    "",
  ];

  for (const { id, label } of PLATFORMS) {
    lines.push(`### ${label}`, "");
    startSteps(id, ctx).forEach((step, i) => {
      lines.push(`${i + 1}. **${step.title}.** ${step.body}`);
      if (step.caution) lines.push(`   > ${step.caution}`);
      if (step.code) lines.push("", ...fence(step.code).map((l) => `   ${l}`), "");
    });
    lines.push("");
  }

  lines.push(
    state.server.storage === "volume"
      ? "The world lives in the Docker volume `mc-data`. Back it up before big changes."
      : "The world and all server files live in the `data/` folder next to this file. Back it up before big changes.",
    "",
  );
  if (state.server.backups) {
    lines.push(`Automatic backups run every ${state.server.backupInterval} into \`backups/\` and are kept for ${state.server.backupKeepDays} days.`, "");
  }

  lines.push("## Connect", "");
  for (const tip of connectTips(port, extraPorts(state).map((p) => p.port))) lines.push(`- **${tip.title}:** ${tip.body}`);
  lines.push("");

  if (players.length > 0) {
    lines.push(
      "## What players need",
      "",
      `Players need Fabric for Minecraft ${state.mcVersion} and these mods. Send them the \`${names.playersFolder}/\` folder`,
      `from this kit: its \`mods/\` folder goes into their Minecraft \`mods\` folder, and \`${names.instructions}\``,
      "walks them through installing Fabric and copying the files.",
      "",
      ...players.map((m) => `- [${m.title}](https://modrinth.com/mod/${m.slug}) ${m.versionNumber}`),
      "",
    );
  } else {
    lines.push("## What players need", "", `Nothing extra: players can join with plain Minecraft ${state.mcVersion}.`, "");
  }

  lines.push("## Everyday commands", "", "| Command | What it does |", "| --- | --- |");
  for (const c of EVERYDAY_COMMANDS) lines.push(`| \`${c.command}\` | ${c.what} |`);
  lines.push(
    "",
    "## Changing mods or settings",
    "",
    "Generate a new compose file, replace `docker-compose.yml`, and run `docker compose up -d`.",
    "Mods removed from the list are deleted from the server automatically. World generation mods",
    "only change terrain that has not been generated yet.",
    "",
    "## Troubleshooting",
    "",
  );
  for (const t of TROUBLESHOOTING) lines.push(`- **${t.symptom}.** ${t.fix}`);
  lines.push(
    "",
    "---",
    "Not an official Minecraft product. Not approved by or associated with Mojang or Microsoft.",
    "",
  );
  return lines.join("\n");
}

/** Zip with a ready-to-run server folder: compose file, README and the players' mods folder. */
export async function buildServerKit(state: BuilderState, onProgress?: (p: DownloadProgress) => void): Promise<Blob> {
  const { folder, playersFolder, compose } = kitNames(state);
  const jars = await fetchPlayerMods(state, onProgress);
  const files: Zippable = {
    [`${folder}/${compose}`]: strToU8(buildCompose(state)),
    [`${folder}/README.md`]: strToU8(buildReadme(state)),
    ...(jars ? playerEntries(state, jars, `${folder}/${playersFolder}/`) : {}),
  };
  return toBlob(zipSync(files, { level: 6 }));
}
