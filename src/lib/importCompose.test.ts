import { describe, expect, it } from "vitest";
import { buildCompose } from "./compose";
import { dep, mod, state } from "./fixtures";
import { importCompose } from "./importCompose";
import { DEFAULT_SERVER } from "./state";

describe("importCompose", () => {
  it("reads the original hand-written compose of this repository", () => {
    const text = [
      "services:",
      "  mc:",
      "    image: itzg/minecraft-server",
      "    ports:",
      '      - "25565:25565/tcp"',
      '      - "24454:24454/udp"',
      "    environment:",
      '      EULA: "TRUE"',
      '      MOTD: "Coolify awet333 Minecraft Server"',
      '      DIFFICULTY: "hard"',
      '      MODE: "survival"',
      '      SEED: "sad46a54sd6a5s4d6a5s4d"',
      '      PVP: "false"',
      '      TYPE: "FABRIC"',
      '      VERSION: "1.21"',
      '      MODRINTH_PROJECTS: "fabric-api:oGwyXeEI, fallingtree:9n1NLElA, tectonic:mSYrCaov, simple-voice-chat:Fku4RjPN"',
      "      MAX_MEMORY: 8G",
      "      INIT_MEMORY: 2G",
    ].join("\n");
    const { patch, modRefs, warnings } = importCompose(text);
    expect(patch.mcVersion).toBe("1.21");
    expect(patch.server).toMatchObject({ motd: "Coolify awet333 Minecraft Server", difficulty: "hard", pvp: false, memory: 8 });
    expect(modRefs).toEqual(["fabric-api", "fallingtree", "tectonic", "simple-voice-chat"]);
    expect(warnings).toEqual([]);
  });

  it("round-trips a file generated by this tool", () => {
    const original = state({
      serverName: "friends",
      server: { ...DEFAULT_SERVER, port: 25570, ops: "Steve, Alex", whitelistEnabled: true, whitelist: "Steve, Alex", maxPlayers: 6 },
      mods: [mod("waystones", { requiredDeps: [dep("balm")] })],
    });
    const { patch, modRefs } = importCompose(buildCompose(original));
    expect(patch.serverName).toBe("friends");
    expect(patch.loaderVersion).toBe("0.16.10");
    expect(patch.server).toEqual(original.server);
    expect(modRefs).toEqual(["waystones", "balm"]);
  });

  it("accepts list-style environments, MEMORY and megabytes", () => {
    const text = ["services:", "  server:", "    image: itzg/minecraft-server:java21", "    environment:", "      - TYPE=PAPER", "      - MEMORY=3072M", "      - VERSION=LATEST"].join("\n");
    const { patch, warnings } = importCompose(text);
    expect(patch.server).toMatchObject({ memory: 3 });
    expect(patch.mcVersion).toBeUndefined();
    expect(warnings).toHaveLength(2);
  });

  it("fails clearly on files without services", () => {
    expect(() => importCompose("version: '3'")).toThrow(/No services/);
  });
});
